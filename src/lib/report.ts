import type { DuplicateGroup } from "./dedupe.js";
import type { PrioritizedTicket } from "./prioritize.js";

export interface ReportInput {
  /** Monday-morning run date, already in the configured timezone. */
  runDate: string;
  /** Window the fetch covered, e.g. "2026-10-05 → 2026-10-12". */
  windowLabel: string;
  sourceName: string;
  ranked: PrioritizedTicket[];
  duplicateGroups: DuplicateGroup[];
  /** Total tickets fetched before any filtering. */
  totalFetched: number;
}

function fmtDate(d: Date): string {
  return d.toISOString().slice(0, 10);
}

/**
 * Builds the Monday-morning pre-read as GitHub-flavored markdown.
 * Pure function — easy to unit test and to preview via `npm run triage:mock`.
 */
export function buildReport(input: ReportInput): string {
  const { runDate, windowLabel, sourceName, ranked, duplicateGroups, totalFetched } =
    input;

  const lines: string[] = [];
  lines.push(`# Backlog triage pre-read — ${runDate}`);
  lines.push("");
  lines.push(
    `_${totalFetched} tickets changed in ${windowLabel} (source: ${sourceName}). ` +
      `Ranked for discussion; duplicates grouped below._`,
  );
  lines.push("");

  // --- Summary stats ---
  const byCat = new Map<string, number>();
  for (const r of ranked) {
    byCat.set(r.classification.category, (byCat.get(r.classification.category) ?? 0) + 1);
  }
  const catSummary = [...byCat.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([c, n]) => `${n} ${c}`)
    .join(" · ");
  lines.push(`**Mix:** ${catSummary || "—"}`);
  const dupCount = duplicateGroups.reduce((n, g) => n + g.duplicates.length, 0);
  if (dupCount > 0) lines.push(`**Likely duplicates:** ${dupCount} tickets`);
  const lowConf = ranked.filter((r) => r.classification.confidence < 0.5).length;
  if (lowConf > 0) lines.push(`**Needs human review:** ${lowConf} (low classification confidence)`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // --- Ranked list ---
  lines.push("## Discuss first");
  lines.push("");
  const discussable = ranked.filter((r) => !r.duplicateOf).slice(0, 10);
  if (discussable.length === 0) {
    lines.push("_Nothing changed this week — enjoy the short triage. ☕_");
  } else {
    for (const [i, r] of discussable.entries()) {
      const t = r.ticket;
      const link = t.url ? ` ([${t.key}](${t.url}))` : ` (${t.key})`;
      lines.push(`### ${i + 1}. ${t.title}${link}`);
      lines.push(`- **Score ${r.score}** · ${r.classification.category} · ${t.status} · opened ${fmtDate(t.createdAt)}`);
      lines.push(`- Why: ${r.rationale.join("; ")}`);
      if (t.description) {
        const snippet = t.description.replace(/\s+/g, " ").slice(0, 220);
        lines.push(`- ${snippet}${t.description.length > 220 ? "…" : ""}`);
      }
      lines.push("");
    }
  }

  // --- Duplicates ---
  if (duplicateGroups.length > 0) {
    lines.push("## Likely duplicates — consider merging");
    lines.push("");
    for (const g of duplicateGroups) {
      lines.push(`- **${g.primary.key}** ${g.primary.title}`);
      for (const d of g.duplicates) {
        lines.push(
          `  - ${d.ticket.key} ${d.ticket.title} _(${(d.similarity * 100).toFixed(0)}% similar)_`,
        );
      }
    }
    lines.push("");
  }

  // --- The rest (below the fold) ---
  const rest = ranked.filter((r) => !r.duplicateOf).slice(10);
  if (rest.length > 0) {
    lines.push("## Also changed (lower priority)");
    lines.push("");
    for (const r of rest) {
      lines.push(
        `- ${r.ticket.key}: ${r.ticket.title} _(score ${r.score}, ${r.classification.category})_`,
      );
    }
    lines.push("");
  }

  lines.push("---");
  lines.push(
    `_Generated by backlog-triage-preread. Scores are heuristic — disagree with the math in triage._`,
  );
  lines.push("");

  return lines.join("\n");
}
